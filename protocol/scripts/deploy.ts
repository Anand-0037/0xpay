import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { encodeFunctionData, type Hex } from 'viem';
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts';
import { deployArtifact, fund, rpc, GATEWAY, EXPLORER } from '../client/src/node.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const artifact = (name: string) => join(root, 'contracts', 'artifacts', `${name}.json`);
const registry = '0xd51c04d7a0b01124e84de152f4e56d9eecb22d2f' as const;
const key = generatePrivateKey();
const address = privateKeyToAccount(key).address;
await mkdir(join(root, 'deployments'), { recursive: true });
await writeFile(join(root, 'deployments', '.deployer-key'), `${key}\n`, { mode: 0o600 });
console.log('deployer', address, 'faucet', await fund(address));
const poseidon = await deployArtifact(key, artifact('Poseidon2'));
console.log('Poseidon2', poseidon);
const verifier = await deployArtifact(key, artifact('Groth16Verifier'));
console.log('Groth16Verifier', verifier);
const pool = await deployArtifact(key, artifact('OxPayPool'), 312_000_000_000_000_000n, [poseidon.address, verifier.address, registry]);
console.log('OxPayPool', pool);
const data = encodeFunctionData({ abi: [{ type: 'function', name: 'getDepositInfo', stateMutability: 'view', inputs: [{ type: 'address' }], outputs: [{ type: 'uint256' }, { type: 'uint32' }, { type: 'uint64' }] }], functionName: 'getDepositInfo', args: [pool.address] });
const stakeRaw = await rpc<Hex>(GATEWAY, 'eth_call', [{ to: registry, data }, 'latest']);
const stake = BigInt(`0x${stakeRaw.slice(2, 66)}`);
if (stake < 12_000_000_000_000_000n) throw new Error(`Stake too low: ${stake}`);
console.log('registry stake wei', stake.toString());
const config = { chainId: 1337, ethrexRpc: 'https://altmempool.forshtat.com', mempoolRpc: GATEWAY, explorer: EXPLORER, pool: pool.address, poseidon: poseidon.address, verifier: verifier.address, registry, deployer: address, deployHash: pool.hash };
await writeFile(join(root, 'deployments', 'devnet.json'), `${JSON.stringify(config, null, 2)}\n`);
console.log('deployment', join(root, 'deployments', 'devnet.json'));
