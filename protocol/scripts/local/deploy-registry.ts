import { readFileSync, writeFileSync } from 'node:fs';
import { createPublicClient, createWalletClient, http, type Hex } from 'viem';
import { privateKeyToAccount } from 'viem/accounts';

const root = '/home/asus/alt/localchain';
const endpoint = 'http://127.0.0.1:10545';
const identity = JSON.parse(readFileSync(`${root}/identity.json`, 'utf8')) as { privateKey: Hex; address: Hex };
const source = readFileSync(`${root}/sidecar/deploy/predeploy/src/protocols/staking-registry-deployment.ts`, 'utf8');
const code = source.match(/STAKING_REGISTRY_INIT_CODE: Hex = "(0x[0-9a-fA-F]+)"/)?.[1] as Hex | undefined;
if (!code) throw new Error('Registry init code missing');
const chain = { id: 1337, name: '0xPay local', nativeCurrency: { name: 'Ether', symbol: 'ETH', decimals: 18 }, rpcUrls: { default: { http: [endpoint] } } } as const;
const account = privateKeyToAccount(identity.privateKey);
if (account.address.toLowerCase() !== identity.address.toLowerCase()) throw new Error('Local identity mismatch');
const publicClient = createPublicClient({ chain, transport: http(endpoint) });
const wallet = createWalletClient({ chain, transport: http(endpoint), account });
const before = await publicClient.getBalance({ address: account.address });
const recipient = '0x1111111111111111111111111111111111111111';
const transfer = await wallet.sendTransaction({ to: recipient, value: 1n, gas: 250_000n, gasPrice: 2_000_000_000n, nonce: await publicClient.getTransactionCount({ address: account.address }) });
const transferReceipt = await publicClient.waitForTransactionReceipt({ hash: transfer });
const afterRecipient = await publicClient.getBalance({ address: recipient });
console.log(JSON.stringify({ transfer, status: transferReceipt.status, block: transferReceipt.blockNumber.toString(), recipientBalance: afterRecipient.toString(), funderBalanceBefore: before.toString() }));
const hash = await wallet.sendTransaction({ data: code, gas: 3_000_000n, gasPrice: 2_000_000_000n });
const receipt = await publicClient.waitForTransactionReceipt({ hash });
if (receipt.status !== 'success' || !receipt.contractAddress) throw new Error(`Registry deployment failed: ${hash}`);
const configPath = `${root}/sidecar/config.json`;
const config = JSON.parse(readFileSync(configPath, 'utf8')) as { stakingRegistryAddress: Hex };
config.stakingRegistryAddress = receipt.contractAddress;
writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`, { mode: 0o600 });
writeFileSync(`${root}/registry.json`, `${JSON.stringify({ address: receipt.contractAddress, hash, block: receipt.blockNumber.toString() }, null, 2)}\n`);
console.log(JSON.stringify({ registry: receipt.contractAddress, hash, status: receipt.status, block: receipt.blockNumber.toString(), codeSize: (await publicClient.getBytecode({ address: receipt.contractAddress }))?.length }));
